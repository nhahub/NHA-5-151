import csv
from numbers import Integral
from pathlib import Path

import torch
from sklearn.model_selection import train_test_split
from torch.utils.data import DataLoader, Dataset
from torchvision import datasets, transforms

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATA = ROOT / "data" / "raw" / "EuroSAT_RGB"
MEAN, STD = (0.5, 0.5, 0.5), (0.5, 0.5, 0.5)
IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)
EUROSAT_CLASS_NAMES = (
    "AnnualCrop",
    "Forest",
    "HerbaceousVegetation",
    "Highway",
    "Industrial",
    "Pasture",
    "PermanentCrop",
    "Residential",
    "River",
    "SeaLake",
)


def make_stratified_splits(targets, seed=42):
    """Create the project's class-stratified 70/15/15 split."""
    indices = list(range(len(targets)))
    train_idx, rest_idx = train_test_split(
        indices, test_size=0.3, stratify=targets, random_state=seed
    )
    val_idx, test_idx = train_test_split(
        rest_idx,
        test_size=0.5,
        stratify=[targets[index] for index in rest_idx],
        random_state=seed,
    )
    return train_idx, val_idx, test_idx


def _validate_split_indices(split_indices, sample_count):
    if len(split_indices) != 3:
        raise ValueError("split_indices must contain train, validation, and test indices.")

    raw_splits = tuple(list(indices) for indices in split_indices)
    flattened = [index for indices in raw_splits for index in indices]
    if any(
        not isinstance(index, Integral) or index < 0 or index >= sample_count
        for index in flattened
    ):
        raise ValueError("split_indices contains an invalid sample index.")
    if len(flattened) != sample_count or len(set(flattened)) != sample_count:
        raise ValueError("split_indices must partition every sample exactly once.")
    if any(not indices for indices in raw_splits):
        raise ValueError("train, validation, and test splits must all be non-empty.")
    return tuple([int(index) for index in indices] for indices in raw_splits)


def _resolve_data_dir(data_dir):
    path = Path(data_dir).expanduser()
    if not path.is_dir():
        parent = path.parent
        if (
            path.name == "EuroSAT_RGB"
            and parent.name == "EuroSAT_RGB"
            and parent.is_dir()
        ):
            if any(
                child.is_dir() and child.name in EUROSAT_CLASS_NAMES
                for child in parent.iterdir()
            ):
                return parent
        raise FileNotFoundError(f"Dataset directory does not exist: {path}")

    if not any(
        child.is_dir() and child.name in EUROSAT_CLASS_NAMES
        for child in path.iterdir()
    ):
        nested = path / "EuroSAT_RGB"
        if nested.is_dir() and any(
            child.is_dir() and child.name in EUROSAT_CLASS_NAMES
            for child in nested.iterdir()
        ):
            return nested
    return path


def load_rgb_split_manifest(data_dir, dataset, seed=42, manifest_dir=None):
    """Load and validate the RGB manifests generated by ``src.split_data``.

    Returns ``None`` only when the default manifest directory is absent, so
    callers can use the deterministic seed-based split before manifests exist.
    """
    is_explicit = manifest_dir is not None
    manifest_dir = (
        Path(manifest_dir)
        if is_explicit
        else ROOT / "data" / "processed" / "splits" / f"seed_{seed}"
    )
    manifest_paths = {
        "train": manifest_dir / "train.csv",
        "validation": manifest_dir / "validation.csv",
        "test": manifest_dir / "test.csv",
    }
    existing = [path.is_file() for path in manifest_paths.values()]
    if not any(existing) and not is_explicit:
        return None
    if not all(existing):
        missing = [
            str(path) for path, is_file in zip(manifest_paths.values(), existing)
            if not is_file
        ]
        raise FileNotFoundError(
            "RGB split manifest is incomplete; missing: " + ", ".join(missing)
        )

    root = Path(data_dir).resolve()
    sample_indices = {
        Path(path).resolve(): (index, label)
        for index, (path, label) in enumerate(dataset.samples)
    }
    class_to_idx = dataset.class_to_idx
    split_indices = []
    seen_indices = set()

    for split_name, manifest_path in manifest_paths.items():
        indices = []
        with manifest_path.open(newline="", encoding="utf-8") as file:
            reader = csv.DictReader(file)
            required_columns = {"image_path", "class_name", "label_id"}
            if not required_columns.issubset(reader.fieldnames or ()):
                raise ValueError(
                    f"{manifest_path} must contain columns "
                    "image_path, class_name, and label_id."
                )
            for row in reader:
                relative_path = Path(row["image_path"])
                if relative_path.is_absolute():
                    raise ValueError(
                        f"RGB split manifest paths must be relative: "
                        f"{row['image_path']}"
                    )
                image_path = (root / relative_path).resolve()
                try:
                    image_path.relative_to(root)
                except ValueError as exc:
                    raise ValueError(
                        f"RGB split manifest path escapes the dataset root: "
                        f"{row['image_path']}"
                    ) from exc
                try:
                    index, actual_label = sample_indices[image_path]
                    label_id = int(row["label_id"])
                except (KeyError, TypeError, ValueError) as exc:
                    raise ValueError(
                        f"Invalid image or label in {manifest_path}: {row}"
                    ) from exc
                class_name = row["class_name"]
                if (
                    label_id != actual_label
                    or class_to_idx.get(class_name) != actual_label
                ):
                    raise ValueError(
                        f"Class mapping mismatch in {manifest_path} for "
                        f"{row['image_path']}: manifest has "
                        f"{class_name!r}/{label_id}, dataset has "
                        f"{dataset.classes[actual_label]!r}/{actual_label}."
                    )
                if index in seen_indices:
                    raise ValueError(
                        f"RGB split manifests contain a duplicate sample: "
                        f"{row['image_path']}"
                    )
                seen_indices.add(index)
                indices.append(index)
        if not indices:
            raise ValueError(f"RGB split manifest is empty: {manifest_path}")
        split_indices.append(indices)

    if len(seen_indices) != len(dataset.samples):
        raise ValueError(
            "RGB split manifests must assign every dataset image exactly once; "
            f"found {len(seen_indices)} assignments for {len(dataset.samples)} images."
        )
    return _validate_split_indices(split_indices, len(dataset.samples))


class TransformSubset(Dataset):
    def __init__(self, base, indices, transform):
        self.base, self.indices, self.transform = base, indices, transform

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, i):
        img, label = self.base[self.indices[i]]
        return self.transform(img), label


def get_loaders(
    data_dir=DEFAULT_DATA,
    batch_size=64,
    seed=42,
    num_workers=2,
    *,
    split_indices=None,
    pretrained=False,
):
    data_dir = _resolve_data_dir(data_dir)
    base = datasets.ImageFolder(str(data_dir))
    if split_indices is None:
        split_indices = make_stratified_splits(base.targets, seed)
    train_idx, val_idx, test_idx = _validate_split_indices(
        split_indices, len(base)
    )

    normalization = (
        transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD)
        if pretrained
        else transforms.Normalize(MEAN, STD)
    )
    model_transforms = [transforms.Resize((224, 224))] if pretrained else []
    train_tf = transforms.Compose([
        transforms.RandomHorizontalFlip(),
        transforms.RandomVerticalFlip(),
        transforms.RandomApply([transforms.RandomRotation((90, 90))], p=0.5),
        *model_transforms,
        transforms.ToTensor(),
        normalization,
    ])
    eval_tf = transforms.Compose([
        *model_transforms,
        transforms.ToTensor(),
        normalization,
    ])

    def loader(indices, tf, shuffle):
        return DataLoader(
            TransformSubset(base, indices, tf),
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            pin_memory=torch.cuda.is_available(),
            generator=torch.Generator().manual_seed(seed),
        )

    return (
        loader(train_idx, train_tf, True),
        loader(val_idx, eval_tf, False),
        loader(test_idx, eval_tf, False),
        base.classes,
    )
